/**
 * PD17 Map — Gutenberg block (editor side).
 *
 * Dynamic block: rendering happens in PHP (render_callback), so `save` returns
 * null and the editor preview is produced with ServerSideRender. Written in
 * plain ES5 against the `wp.*` globals, so no build step is required.
 */
( function ( wp, data ) {
	'use strict';

	var el = wp.element.createElement;
	var __ = wp.i18n.__;
	var registerBlockType = wp.blocks.registerBlockType;
	var useBlockProps = wp.blockEditor.useBlockProps;
	var InspectorControls = wp.blockEditor.InspectorControls;
	var PanelBody = wp.components.PanelBody;
	var TextControl = wp.components.TextControl;
	var TextareaControl = wp.components.TextareaControl;
	var SelectControl = wp.components.SelectControl;
	var ServerSideRender = wp.serverSideRender;

	var T = data || {};
	var USE_DEFAULT = { label: __( 'Use the plugin setting', 'prodev17-location-map' ), value: '' };
	var YES_NO = [
		USE_DEFAULT,
		{ label: __( 'Yes', 'prodev17-location-map' ), value: 'yes' },
		{ label: __( 'No', 'prodev17-location-map' ), value: 'no' }
	];

	function withDefault( list ) {
		return [ USE_DEFAULT ].concat( list || [] );
	}

	registerBlockType( 'prodev17/location-map', {
		edit: function ( props ) {
			var a = props.attributes;
			var set = props.setAttributes;

			return el(
				'div',
				useBlockProps(),
				el(
					InspectorControls,
					{},
					el(
						PanelBody,
						{ title: __( 'Map', 'prodev17-location-map' ), initialOpen: true },
						el( TextControl, {
							label: __( 'Latitude', 'prodev17-location-map' ),
							value: a.lat,
							onChange: function ( v ) { set( { lat: v } ); }
						} ),
						el( TextControl, {
							label: __( 'Longitude', 'prodev17-location-map' ),
							value: a.lng,
							onChange: function ( v ) { set( { lng: v } ); }
						} ),
						el( TextControl, {
							label: __( 'Zoom (1–20)', 'prodev17-location-map' ),
							value: a.zoom,
							onChange: function ( v ) { set( { zoom: v } ); }
						} ),
						el( TextControl, {
							label: __( 'Height (px)', 'prodev17-location-map' ),
							value: a.height,
							onChange: function ( v ) { set( { height: v } ); }
						} ),
						el( TextControl, {
							label: __( 'Title', 'prodev17-location-map' ),
							value: a.title,
							onChange: function ( v ) { set( { title: v } ); }
						} ),
						el( TextareaControl, {
							label: __( 'Address', 'prodev17-location-map' ),
							value: a.address,
							onChange: function ( v ) { set( { address: v } ); }
						} )
					),
					el(
						PanelBody,
						{ title: __( 'Look and behaviour', 'prodev17-location-map' ), initialOpen: false },
						el( SelectControl, {
							label: __( 'Base style', 'prodev17-location-map' ),
							value: a.style,
							options: withDefault( T.styles ),
							onChange: function ( v ) { set( { style: v } ); }
						} ),
						el( SelectControl, {
							label: __( 'Palette', 'prodev17-location-map' ),
							value: a.palette,
							options: withDefault( T.palettes ),
							onChange: function ( v ) { set( { palette: v } ); }
						} ),
						el( SelectControl, {
							label: __( 'Label language', 'prodev17-location-map' ),
							value: a.lang,
							options: withDefault( T.languages ),
							onChange: function ( v ) { set( { lang: v } ); }
						} ),
						el( SelectControl, {
							label: __( 'Fullscreen button', 'prodev17-location-map' ),
							value: a.fullscreen,
							options: YES_NO,
							onChange: function ( v ) { set( { fullscreen: v } ); }
						} ),
						el( SelectControl, {
							label: __( 'Address search', 'prodev17-location-map' ),
							value: a.search,
							options: YES_NO,
							onChange: function ( v ) { set( { search: v } ); }
						} )
					)
				),
				el( ServerSideRender, {
					block: 'prodev17/location-map',
					attributes: a
				} )
			);
		},

		// Dynamic block: the markup is generated by PHP.
		save: function () {
			return null;
		}
	} );
} )( window.wp, window.PD17MapBlock );
